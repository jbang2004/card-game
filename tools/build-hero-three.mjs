import { build } from "esbuild";
import { writeFile, mkdir, readFile } from "node:fs/promises";
await mkdir("src/vendor", { recursive: true });
const license = (await readFile("node_modules/three/LICENSE", "utf8")).replace(
  /(Copyright[^\n]*\n)/,
  "$1Copyright (C) 2016-2026, by Arseny Kapoulkine (arseny.kapoulkine@gmail.com), meshoptimizer decoder\n",
);
await build({
  entryPoints: ["tools/hero-three-entry.js"],
  outfile: "src/vendor/hero-three.js",
  bundle: true,
  minify: true,
  format: "iife",
  globalName: "EmberHeroThree",
  target: ["es2020"],
  legalComments: "eof",
  banner: {
    js:
      "/* Generated by npm run vendor:hero. Three.js 0.186.0.\n" +
      license +
      "*/",
  },
});
await writeFile("src/vendor/hero-three.LICENSE.txt", license);
